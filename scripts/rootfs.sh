#!/usr/bin/env bash
# Build a Debian (bookworm, arm64) rootfs image for the Moto Z2 Play (albus).
# Requires scripts/kernel.sh to have run first (modules in out/).
set -euxo pipefail

ROOT="$PWD"
OUT="$ROOT/out"
WORK="$ROOT/rootfs-work"
IMG="$OUT/debian-albus.ext4"
SIZE_MB=6144

DEB_CODENAME=bookworm
DEB_MIRROR=http://deb.debian.org/debian

test -d "$OUT"
MODSRC="$(ls -d "$OUT"/modules-* | head -n1)"
KREL="$(basename "$MODSRC")"
KREL="${KREL#modules-}"
test -n "$KREL"

rm -rf "$WORK"
mkdir -p "$WORK"
TREE="$WORK/rootfs"

debootstrap --arch=arm64 --variant=minbase --foreign \
	--include=systemd,systemd-sysv,dbus,network-manager,wpasupplicant,openssh-server,dnsmasq,iproute2,e2fsprogs,ca-certificates,wireless-regdb \
	"$DEB_CODENAME" "$TREE" "$DEB_MIRROR"

# Do NOT run debootstrap --second-stage: it executes maintainer scripts
# (postinst) under qemu-user emulation, which is fragile (e.g. polkitd).
# Instead, complete the system state deliberately, on the host, below.
rm -rf "$TREE/debootstrap"

# Mark every unpacked package as installed in the dpkg database. The
# postinst side effects that this rootfs actually needs (system users,
# SSH host keys, CA bundle, service enablement) are recreated below by
# hand; the rest are boot-time no-ops.
python3 - "$TREE" <<'PY'
import sys, os
tree = sys.argv[1]
status = os.path.join(tree, "var/lib/dpkg/status")
with open(status) as f:
    data = f.read()
data = data.replace("Status: install ok unpacked\n", "Status: install ok installed\n")
data = data.replace("Status: install ok half-configured\n", "Status: install ok installed\n")
with open(status, "w") as f:
    f.write(data)
print("dpkg status entries marked configured")
PY

# System users and groups the services require (these are normally created
# by package postinsts, which we skipped). Deterministic id allocation.
python3 - "$TREE" <<'PY'
import sys, os
tree = sys.argv[1]

def add_unique(path, lines, key_idx=0, keys=()):
    p = os.path.join(tree, path)
    existing = set()
    if os.path.exists(p):
        with open(p) as f:
            for ln in f:
                existing.add(ln.split(":")[key_idx])
    with open(p, "a") as f:
        for ln in lines:
            k = ln.split(":")[key_idx]
            if k not in existing:
                f.write(ln + "\n")

USERS = {
    "passwd": [
        "messagebus:x:104:104:daemon:/nonexistent:/usr/sbin/nologin",
        "dnsmasq:x:105:105:dnsmasq daemon:/var/lib/misc:/usr/sbin/nologin",
        "sshd:x:106:106:sshd privilege separation:/run/sshd:/usr/sbin/nologin",
        "_polkitd:x:107:107:polkit daemon:/nonexistent:/usr/sbin/nologin",
        "_apt:x:108:65534:apt package manager:/nonexistent:/usr/sbin/nologin",
    ],
    "group": [
        "messagebus:x:104:",
        "dnsmasq:x:105:",
        "sshd:x:106:",
        "polkitd:x:107:",
        "_apt:x:108:",
    ],
    "shadow": [
        "messagebus:!::0::::::",
        "dnsmasq:!::0::::::",
        "sshd:!::0::::::",
        "_polkitd:!::0::::::",
        "_apt:!::0::::::",
    ],
    "gshadow": [
        "messagebus:!::",
        "dnsmasq:!::",
        "sshd:!::",
        "polkitd:!::",
    ],
}
for name, lines in USERS.items():
    add_unique(name, lines)
    print("userdb:", name, "updated")
PY

mkdir -p "$TREE/run/sshd"

# SSH host keys (normally generated by the openssh-server postinst).
for kt in rsa ecdsa ed25519; do
	test -f "$TREE/etc/ssh/ssh_host_${kt}_key" || \
		ssh-keygen -q -t "$kt" -N "" -f "$TREE/etc/ssh/ssh_host_${kt}_key"
done
test -f "$TREE/etc/ssh/ssh_host_ed25519_key"

# CA bundle (normally generated by the ca-certificates postinst).
mkdir -p "$TREE/etc/ssl/certs"
cat "$TREE"/usr/share/ca-certificates/mozilla/*.crt \
	> "$TREE/etc/ssl/certs/ca-certificates.crt" 2>/dev/null || true
test -s "$TREE/etc/ssl/certs/ca-certificates.crt"

# Unset machine-id so systemd generates one cleanly at first boot.
: > "$TREE/etc/machine-id"

# Static DNS fallback; NetworkManager rewrites this at wifi activation.
printf 'nameserver 1.1.1.1\nnameserver 8.8.8.8\n' > "$TREE/etc/resolv.conf"

# Passwordless root over USB RNDIS (empty password, cleared via /etc/shadow).
sed -i 's|^root:[^:]*:|root::|' "$TREE/etc/shadow"
test "$(grep '^root:' "$TREE/etc/shadow" | cut -d: -f2)" = ""

# Debian enables dnsmasq.service by default; it would fight with the
# dnsmasq instance started by usb-gadget.service on the gadget interface.
rm -f "$TREE/etc/systemd/system/multi-user.target.wants/dnsmasq.service" \
	  "$TREE/etc/systemd/system/sockets.target.wants/dnsmasq.socket"

echo albus > "$TREE/etc/hostname"
cp -a "$ROOT/overlay/." "$TREE/"
chmod 755 "$TREE/usr/local/bin/albus-usb-gadget" \
	  "$TREE/usr/local/bin/albus-resize" \
	  "$TREE/usr/local/bin/albus-debug"

# Enable the needed units through the multi-user target wants-tree so no
# systemctl has to run inside the foreign-architecture chroot.
mkdir -p "$TREE/etc/systemd/system/multi-user.target.wants"
ln -sf /lib/systemd/system/ssh.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/ssh.service"
ln -sf /lib/systemd/system/NetworkManager.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/NetworkManager.service"
ln -sf /etc/systemd/system/usb-gadget.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/usb-gadget.service"
ln -sf /etc/systemd/system/albus-resize.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/albus-resize.service"

# Kernel modules (dependency cache already generated by modules_install).
mkdir -p "$TREE/lib/modules"
cp -a "$MODSRC/lib/modules/$KREL" "$TREE/lib/modules/"

# Device firmware from the albus-firmware repository:
#  - wcnss.mdt + segments: firm-root (remoteproc default "wcnss.mdt")
#  - mba/modem/adsp/venus: firmware root (for future remoteproc bring-up)
#  - wlan NV files + a506_zap: device directory (DT firmware-name paths)
FW="$WORK/albus-firmware"
rm -rf "$FW"
git clone --depth 1 \
	https://gitlab.com/vanadium-oss/msm8953/moto/albus/Mainline/albus-firmware.git "$FW"
mkdir -p "$TREE/lib/firmware/qcom/msm8953/motorola/albus"
cp -a "$FW"/wlan/* \
	"$TREE"/lib/firmware/qcom/msm8953/motorola/albus/
cp -a "$FW"/modem/image/a506_zap.* \
	"$TREE"/lib/firmware/qcom/msm8953/motorola/albus/
cp -a "$FW"/modem/image/wcnss.* "$TREE"/lib/firmware/
cp -a "$FW"/modem/image/mba.mbn "$FW"/modem/image/modem.* \
	"$FW"/modem/image/adsp.* "$FW"/modem/image/venus.* \
	"$TREE"/lib/firmware/

# Pack the ext4 image.
truncate -s "$SIZE_MB"M "$IMG"
mkfs.ext4 -F -q -L debian-albus -E lazy_itable_init=0,lazy_journal_init=0 "$IMG"
MNT="$WORK/mnt"
mkdir -p "$MNT"
mount -o loop "$IMG" "$MNT"
cp -a "$TREE/." "$MNT/"
umount "$MNT"
sync

gzip -6 -c "$IMG" > "$OUT/debian-albus.ext4.gz"
sha256sum "$OUT/debian-albus.ext4.gz" > "$OUT/debian-albus.ext4.gz.sha256"
rm -f "$IMG"
