#!/usr/bin/env bash
# Build a Debian (bookworm, arm64) rootfs image for the Moto Z2 Play (albus).
# Requires scripts/kernel.sh to have run first (modules in out/).
set -euxo pipefail

ROOT="$PWD"
OUT="$ROOT/out"
WORK="$ROOT/rootfs-work"
IMG="$OUT/debian-albus.ext4"
SIZE_MB=6144

DEB_CODENAME=bookworm
DEB_MIRROR=http://deb.debian.org/debian

test -d "$OUT"
MODSRC="$(ls -d "$OUT"/modules-* | head -n1)"
KREL="$(basename "$MODSRC")"
KREL="${KREL#modules-}"
test -n "$KREL"

rm -rf "$WORK"
mkdir -p "$WORK"
TREE="$WORK/rootfs"

debootstrap --arch=arm64 --variant=minbase --foreign \
	--include=systemd,systemd-sysv,dbus,network-manager,wpasupplicant,openssh-server,dnsmasq,iproute2,e2fsprogs,ca-certificates,wireless-regdb \
	"$DEB_CODENAME" "$TREE" "$DEB_MIRROR"

cp /usr/bin/qemu-aarch64-static "$TREE/usr/bin/"
chroot "$TREE" /debootstrap/debootstrap --second-stage
rm -f "$TREE/usr/bin/qemu-aarch64-static"
rm -rf "$TREE/debootstrap"

# Passwordless root over USB RNDIS (empty password, cleared via /etc/shadow).
sed -i 's|^root:[^:]*:|root::|' "$TREE/etc/shadow"
test "$(grep '^root:' "$TREE/etc/shadow" | cut -d: -f2)" = ""

# Debian enables dnsmasq.service by default; it would fight with the
# dnsmasq instance started by usb-gadget.service on the gadget interface.
rm -f "$TREE/etc/systemd/system/multi-user.target.wants/dnsmasq.service" \
	  "$TREE/etc/systemd/system/sockets.target.wants/dnsmasq.socket"

echo albus > "$TREE/etc/hostname"
cp -a "$ROOT/overlay/." "$TREE/"
chmod 755 "$TREE/usr/local/bin/albus-usb-gadget" \
	  "$TREE/usr/local/bin/albus-resize" \
	  "$TREE/usr/local/bin/albus-debug"

# Enable the needed units through the multi-user target wants-tree so no
# systemctl has to run inside the foreign-architecture chroot.
mkdir -p "$TREE/etc/systemd/system/multi-user.target.wants"
ln -sf /lib/systemd/system/ssh.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/ssh.service"
ln -sf /lib/systemd/system/NetworkManager.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/NetworkManager.service"
ln -sf /etc/systemd/system/usb-gadget.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/usb-gadget.service"
ln -sf /etc/systemd/system/albus-resize.service \
	"$TREE/etc/systemd/system/multi-user.target.wants/albus-resize.service"

# Kernel modules (dependency cache already generated by modules_install).
mkdir -p "$TREE/lib/modules"
cp -a "$MODSRC/lib/modules/$KREL" "$TREE/lib/modules/"

# Device firmware from the albus-firmware repository:
#  - wcnss.mdt + segments: firm-root (remoteproc default "wcnss.mdt")
#  - mba/modem/adsp/venus: firmware root (for future remoteproc bring-up)
#  - wlan NV files + a506_zap: device directory (DT firmware-name paths)
FW="$WORK/albus-firmware"
rm -rf "$FW"
git clone --depth 1 \
	https://gitlab.com/vanadium-oss/msm8953/moto/albus/Mainline/albus-firmware.git "$FW"
mkdir -p "$TREE/lib/firmware/qcom/msm8953/motorola/albus"
cp -a "$FW"/wlan/* \
	"$TREE"/lib/firmware/qcom/msm8953/motorola/albus/
cp -a "$FW"/modem/image/a506_zap.* \
	"$TREE"/lib/firmware/qcom/msm8953/motorola/albus/
cp -a "$FW"/modem/image/wcnss.* "$TREE"/lib/firmware/
cp -a "$FW"/modem/image/mba.mbn "$FW"/modem/image/modem.* \
	"$FW"/modem/image/adsp.* "$FW"/modem/image/venus.* \
	"$TREE"/lib/firmware/

# Pack the ext4 image.
truncate -s "$SIZE_MB"M "$IMG"
mkfs.ext4 -F -q -L debian-albus -E lazy_itable_init=0,lazy_journal_init=0 "$IMG"
MNT="$WORK/mnt"
mkdir -p "$MNT"
mount -o loop "$IMG" "$MNT"
cp -a "$TREE/." "$MNT/"
umount "$MNT"
sync

gzip -6 -c "$IMG" > "$OUT/debian-albus.ext4.gz"
sha256sum "$OUT/debian-albus.ext4.gz" > "$OUT/debian-albus.ext4.gz.sha256"
rm -f "$IMG"
